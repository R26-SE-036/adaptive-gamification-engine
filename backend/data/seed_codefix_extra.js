function validate() {
    const problems = [];
    const ids = new Set();

    for (const item of QUESTIONS) {
        if (ids.has(item.id)) problems.push(`${item.id}: duplicate id`);
        ids.add(item.id);

        if (!Array.isArray(item.correctAnswer) || item.correctAnswer.length === 0) {
            problems.push(`${item.id}: no accepted answers`);
            continue;
        }
        if (!Number.isInteger(item.buggyLineIndex) ||
            item.buggyLineIndex < 0 ||
            item.buggyLineIndex >= item.codeLines.length) {
            problems.push(`${item.id}: buggyLineIndex out of range`);
            continue;
        }

        const buggy = normaliseJavaLine(item.codeLines[item.buggyLineIndex]);
        for (const answer of item.correctAnswer) {
            const normalised = normaliseJavaLine(answer);
            if (!normalised) problems.push(`${item.id}: an answer normalises to nothing`);
            // The whole point of the question is that the fix differs from the
            // line being fixed. If they match, the question is already solved.
            if (normalised === buggy) problems.push(`${item.id}: an answer equals the buggy line`);
        }

        if ((item.hints || []).length < 3) problems.push(`${item.id}: fewer than 3 hints`);
        if (!item.explanation) problems.push(`${item.id}: no explanation`);
    }

    return problems;
}

const seed = async () => {
    const problems = validate();
    if (problems.length > 0) {
        console.error('Refusing to seed. Problems found:');
        problems.forEach((p) => console.error('  ' + p));
        process.exit(1);
    }

    await mongoose.connect(process.env.MONGODB_URI);

    for (const question of QUESTIONS) {
        await QuestionBank.updateOne({ id: question.id }, { $set: question }, { upsert: true });
    }

    const total = await QuestionBank.countDocuments({ gameType: 'CodeFix' });
    console.log(`Upserted ${QUESTIONS.length} CodeFix questions. Bank holds ${total}.`);

    await mongoose.disconnect();
};

module.exports = { QUESTIONS, validate };

if (require.main === module) {
    seed().catch((error) => {
        console.error(error.message);
        process.exit(1);
    });
}
