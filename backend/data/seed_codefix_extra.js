/**
 * Additional CodeFix questions, to fill the last single-question slots.
 *
 *     node data/seed_codefix_extra.js
 *
 * Idempotent - upserted by id. Validates before writing.
 *
 * ========================== WHY THESE WERE NEEDED ==========================
 * CodeFix covers 14 concepts at 5 levels - 70 slots - and every one of them held
 * exactly one question. A student who met a slot twice was guaranteed to be
 * shown the same broken code, and having already typed the fix once the second
 * visit taught them nothing.
 *
 * These add two per slot, so a student can work a level without repeating.
 *
 * ============================ WHAT A GOOD ONE IS ============================
 * A different SHAPE of the same mistake, not the same snippet with new
 * variable names. The three questions in a slot should fail for the same
 * underlying reason and look nothing alike - a student who has memorised one
 * fix should still have to understand the second.
 *
 * `correctAnswer` lists every accepted form. Whitespace outside string literals
 * is insignificant (see services/gradingService.js), so only genuinely
 * different fixes need listing - not spacing variants.
 */

